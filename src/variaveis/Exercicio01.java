package variaveis;

public class Exercicio01 {
    public static void main(String[] args) {
        // Declaração de Variaveis.
        String nome = "Juliana";
        int numero = 55;
        double numeroDecimal = 9.903;
        boolean ativado = false;
        char letra = 'C';

        // saida de Dados utilizando as variaveis.
        System.out.println("Meu nome é: " + nome);
        System.out.println("Bom dia, " + nome + "!");
        System.out.println("Texto: " + "Olá, Mundo!!!");
        System.out.println("Numero Inteiro: " + numero);
        System.out.println("Numero decimal: " + numeroDecimal);
        System.out.println("Booleano: " + ativado);
        System.out.println("Caractere: " + letra);
    }
}

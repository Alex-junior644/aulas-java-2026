package introducaoaojava;

public class SaidaDeDados {
    public static void main(String[] args) {

        // Saída de Dados (Tipos de dados Primitivos)
        System.out.println("Boa noite, Meu nome é Alex."); // Texto
        System.out.println(1000); // Numero Inteiro
        System.out.println(8.5); // Numero Decimal
        System.out.println(true); // Booleano
        System.out.println('A'); // Caractere
    }

}

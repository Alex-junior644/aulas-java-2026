package variaveis;

public class EstudandoVariaves {
    public static void main(String[] args) {
        /**
         * A execução do código sempre vai acontecer no sentido de cima para baixo e da esquerda para direita.
         *
         * Toda variavel antes de ser utilizada deve ser declarada (criada). Após a sua declaração esta variavel
         * pode ser utilizada em qualquer lugar do meo codigo.
         */

        String nome = "Jõao";
        int numero = 100;
        System.out.println(numero);
        System.out.println(nome);
    }
}
